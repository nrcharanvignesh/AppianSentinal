import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const desktop = join(dirname(fileURLToPath(import.meta.url)), '..');
const repository = join(desktop, '..');
const output = join(desktop, 'lib', 'sail-tokens.js');
const python = [
  'import json',
  'from appian_sentinel.knowledge.skill_loader import get_ref_prefixes',
  'from appian_sentinel.parser.sail_catalog import build_default_sail_catalog',
  // Use the merged catalog, not skill_loader alone: the archive yields 589 callables and the
  // validator adds 80 observed only in real exports. Highlighting the smaller set would render
  // 80 callables the validator accepts as plain text.
  'print(json.dumps({',
  '  "callables": sorted(build_default_sail_catalog().valid or []),',
  '  "prefixes": sorted(get_ref_prefixes() or []),',
  '}))',
].join('\n');

const result = spawnSync('python', ['-c', python], {
  cwd: repository,
  encoding: 'utf8',
});
if (result.status !== 0) {
  throw new Error(result.stderr || 'Could not load appian.skill.');
}

const tokens = JSON.parse(result.stdout);
const source = [
  '// Generated by scripts/gen-sail-tokens.mjs from appian.skill. Do not edit.',
  `export const SAIL_CALLABLES = new Set(${JSON.stringify(tokens.callables)});`,
  `export const SAIL_REF_PREFIXES = new Set(${JSON.stringify(tokens.prefixes)});`,
  '',
].join('\n');
writeFileSync(output, source, 'ascii');
console.log(`[SUCCESS] Wrote ${tokens.callables.length} callables and ${tokens.prefixes.length} prefixes.`);
